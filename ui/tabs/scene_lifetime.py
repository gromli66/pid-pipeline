# -*- coding: utf-8 -*-
"""Сцена редактора обязана умирать вместе со своим виджетом (пункт 1-46).

⛔ **Корень крахов базового гейта `0xC0000005`, названный вмешательством,
а не рассуждением** (замеры `MEASUREMENTS §119в–§119д`). `QGraphicsScene`
во всех редакторах создаётся БЕЗ родителя Qt (`QGraphicsScene()`, пять мест)
и держится только питоньим полем редактора. Значит она ПЕРЕЖИВАЕТ
разрушенную вкладку и умирает позже — по воле сборщика мусора, — а у её
BSP-индекса (`QGraphicsSceneBspTreeIndex`, приватный объект Qt без питоньей
обёртки) к этому моменту взведён НУЛЕВОЙ таймер: индекс заводит его на каждом
добавлении/удалении элемента. Тик такого таймера диспетчер доставляет по
мёртвому получателю — нативный стек снят на замороженном процессе:
`QEventDispatcherWin32::event` → `QCoreApplication::notifyInternal2` по
освобождённой памяти. Это и есть `access violation` базового гейта; в части
прогонов та же порча кучи всплывает раньше и даёт `0xC0000374`.

Вмешательство подтвердило корень ДВАЖДЫ на воспроизводимой паре наборов:
без правки — **4 краха из 4**; снять BSP-индекс (`NoIndex`) — **0 из 4**;
дать сцене родителя — **0 из 4**.

⛔ `NoIndex` лечением НЕ выбран: он делает поиск элемента линейным, а сцены
редакторов несут по две тысячи элементов и обслуживают мышь оператора.
Выбрано родительство: сцена живёт ровно столько, сколько виджет, который её
показывает, и умирает СИНХРОННО с ним, в главном потоке, вместе с таймером
своего индекса.

⚠ Правка стоит у ВКЛАДОК, а не у редакторов, сознательно: `ui/editors/`
в этот момент правит другой пункт дороги (1-40). Одна строка `QGraphicsScene(self)`
в каждом редакторе была бы точнее по адресу, и она названа в журнале как
предложение владельцу зоны.
"""

from PySide6.QtWidgets import QGraphicsScene


def adopt_editor_scene(editor) -> bool:
    """Отдать сцену редактора под родительство самого редактора.

    Возвращает, нашлась ли бесхозная сцена. Поле ищется в `__dict__`, а не
    через `getattr`: у `QGraphicsView` есть МЕТОД `scene()`, и одноимённое
    поле редактора его затеняет — `getattr` на редакторе без поля вернул бы
    метод, а не сцену.
    """
    if editor is None:
        return False
    for attr in ("scene", "scene_obj"):
        scene = editor.__dict__.get(attr)
        if isinstance(scene, QGraphicsScene) and scene.parent() is None:
            scene.setParent(editor)
            return True
    return False
