"""Одна дверь запрета слепой перезаписи — на все вкладки, которые пишут.

Запрет ввёл пункт 1.x9 в `BaseGraphTab`, а 1.x14 повторил его в
`OcrBindingTab`, потому что та не наследует базовый класс. Две реализации
одного запрета — готовое расхождение ровно того класса, что 1-18 нашёл
у дверей вопроса о несохранённом: там ДВЕ двери успели разойтись в ЧЕТЫРЁХ
клетках из четырёх, и совпадение текста диалогов ни одной из них бы не
поймало. Пункт 1-41 сводит их в одну и добавляет к ней ещё две вкладки —
масок труб и перекрёстков.

**Что запрет делает.** Артефакт, который не удалось прочитать НЕ по 404,
попадает в `_unreadable_on_server`: его состояние на сервере неизвестно, а
вкладка собрана вслепую. Запись в такой артефакт ждёт явного «да» оператора.
«Да» снимает запрет насовсем (решение принял оператор), «нет» отменяет
сохранение целиком и возвращает вопрос при следующей попытке; обе ветки
пишут строку в лог клиента.

⛔ **Сохранение ПО ТАЙМЕРУ вопроса не задаёт** (пункт 1-38): «да» вслепую
снял бы запрет насовсем, то есть автосохранение отменило бы защиту без
оператора. Тик отказывается от записи и говорит об этом строкой, а запрет
оставляет взведённым.

⛔ **Разрешение засчитывается, только если разрешены ВСЕ спрошенные артефакты**
(пункт 1.x14): «да» первому при «нет» второму ничего не записало, значит и
разрешения оператор не давал.
"""

from __future__ import annotations

import logging

from PySide6.QtWidgets import QMessageBox


class BlindOverwriteGuard:
    """Реестр непрочитанного на сервере + вопрос перед записью в него.

    Подмешивается вкладке; та обязана позвать `_init_blind_overwrite()` в
    своём `__init__` и объявить `_BLIND_WRITE_WARNING` — «артефакт → о чём
    предупредить, если писать в него придётся вслепую».
    """

    #: артефакт → о чём предупредить, если писать в него придётся вслепую
    _BLIND_WRITE_WARNING: dict[str, str] = {}

    #: `(ключ_отказа_загрузчика, артефакт, заголовок модалки, текст)` — что
    #: вкладка считает «серверную копию прочитать не удалось». Ключ приезжает
    #: полем `Job.failure_key`; вкладка, объявившая `failure_key` и не внёсшая
    #: его сюда, предупреждения не покажет — это сторожится сценарием.
    _UNREADABLE_FLAGS: tuple = ()

    def _init_blind_overwrite(self) -> None:
        #: артефакты, чьё состояние на сервере НЕИЗВЕСТНО: прочитать не удалось
        #: не по 404. Запись в них ждёт явного «да» оператора.
        self._unreadable_on_server: set[str] = set()

    @property
    def _blind_log(self) -> logging.Logger:
        """Логгер ВКЛАДКИ, а не общей двери.

        Д2 требует след, по которому видно, ЧТО происходило у оператора;
        общий логгер `ui.tabs.blind_overwrite` этого не даёт — в `client.log`
        все четыре вкладки слились бы в один источник. Поэтому дверь пишет
        от имени модуля вкладки, как писала каждая копия до сведения.
        """
        return logging.getLogger(type(self).__module__)

    def _ask_yes_cancel(self, title: str, text: str) -> bool:
        """Вопрос «да / отмена» РУССКИМИ кнопками. `True` — оператор согласился.

        Своя сборка, а не `QMessageBox.question`: у статической двери подписи
        кнопок стандартные, то есть английские — замер этой сессии на боевом
        PySide6 дал `['Cancel', '&Yes']`, — а `QTranslator` в проекте не
        установлен вовсе. Прецедент своей сборки — диалог конфликта диаметров
        (`ocr_binding_editor.py:2265-2267`).

        Одна на оба вопроса графовых вкладок (запрет слепой перезаписи и
        «Подтвердить»), чтобы они не разошлись, как разошлись две двери
        вопроса о несохранённом (пункт 1-18, четыре клетки из четырёх).
        """
        box = QMessageBox(QMessageBox.Icon.Question, title, text,
                          QMessageBox.StandardButton.NoButton, self)
        yes = box.addButton("Да", QMessageBox.ButtonRole.YesRole)
        cancel = box.addButton("Отмена", QMessageBox.ButtonRole.RejectRole)
        box.setDefaultButton(cancel)
        box.exec()
        return box.clickedButton() is yes

    def _note_unreadable(self, artifacts: dict) -> None:
        """Разложить флаги отказа по реестру и предупредить оператора.

        Один проход на все артефакты вкладки: раньше каждая вкладка
        раскладывала свои флаги руками, и добавление артефакта означало ещё
        одну копию того же цикла плюс ещё одну копию модалки.

        Зовётся и НЕ ТОЛЬКО после загрузки: «файл лёг, но не читается» —
        отказ того же смысла (серверная копия неизвестна), поэтому разбор
        скачанного передаёт сюда тот же ключ синтетическим словарём.
        """
        for flag, artifact, title, text in self._UNREADABLE_FLAGS:
            if not artifacts.get(flag) or artifact in self._unreadable_on_server:
                continue
            self._unreadable_on_server.add(artifact)
            self._blind_log.warning(
                "%s не прочитан на сервере — вкладка собрана вслепую", artifact)
            QMessageBox.warning(self, title, text)

    def _confirm_blind_overwrite(self, *artifacts: str) -> bool:
        """Разрешена ли запись в артефакты, чьё состояние на сервере неизвестно.

        Спрашивается ровно про те артефакты, в которые пишет вызывающий метод:
        запрет АДРЕСНЫЙ, отказ соседа запись не запирает. Про артефакт вне
        реестра вопроса нет.
        """
        allowed = []
        for artifact in artifacts:
            if artifact not in self._unreadable_on_server:
                continue
            if not self._save_interactive:
                self._refuse_save("⚠️ Автосохранение отменено: серверная копия "
                                  "не прочитана — сохраните вручную")
                return False
            if not self._ask_yes_cancel(
                "Сохранение затрёт серверную копию",
                f"{self._BLIND_WRITE_WARNING[artifact]}\n\nСохранить всё равно?",
            ):
                self._blind_log.warning(
                    "запись в %s отменена оператором: серверная копия "
                    "не прочитана", artifact)
                return False
            allowed.append(artifact)

        for artifact in allowed:
            self._blind_log.warning(
                "оператор разрешил перезапись %s поверх непрочитанной "
                "серверной копии", artifact)
            self._unreadable_on_server.discard(artifact)
        return True
