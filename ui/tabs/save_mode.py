# -*- coding: utf-8 -*-
"""Неинтерактивный режим сохранения — сохранение ПО ТАЙМЕРУ не спрашивает.

Зачем это здесь, а не в `ui/services/autosave.py`. Сервис автосохранения
диалогов не поднимает и заглушить их не может: они сидят у самих методов
сохранения — вопрос о слепой перезаписи (`_confirm_blind_overwrite`, пункты
1-33 и 1-39) и предупреждения об отказе записи. Поэтому право задавать вопросы
принадлежит ВКЛАДКЕ, а сервис его лишь временно отнимает на время тика.

Цена фонового диалога замерена (`MEASUREMENTS §93`): тик раз в 120 с встаёт
посреди работы оператора, а «Да» в вопросе о слепой перезаписи СНИМАЕТ запрет
насовсем — то есть автосохранение способно молча отменить только что купленную
защиту. Отсюда правило: по таймеру вкладка не спрашивает, а ОТКАЗЫВАЕТСЯ
и говорит об этом строкой; ручное сохранение по-прежнему спрашивает.

⛔ Режим не обходит запрет 1-33/1-39, а подчиняется ему: молчаливый отказ
оставляет запрет взведённым, и ближайший ручной заход спросит снова.
"""
import logging
from contextlib import contextmanager

logger = logging.getLogger(__name__)

#: Машинный признак отказа гейта пересборки — КОПИЯ `app.api.build_gate
#: .REBUILD_REFUSAL`. Копия, а не импорт: клиент пакуется PyInstaller-ом
#: отдельно от сервера и `app.api` в сборку не тянет. Сведение обеих копий
#: держит `tests/test_graph_rebuild_gate.py`.
REBUILD_REFUSAL = "graph_rebuilding"

#: Что видит оператор, когда его правки повисли в воздухе.
REBUILD_BANNER = ("⛔ Граф пересобран заново — эта вкладка держит СТАРУЮ схему, "
                  "и сохранить её больше некуда. Закройте вкладку и откройте "
                  "заново; автосохранение остановлено.")


class NonInteractiveSaveMixin:
    """Право вкладки задавать вопросы во время сохранения.

    Носителями обязаны быть ВСЕ классы карты `autosave._SAVE_METHODS`: она
    копируется строкой, и класс, попавший в неё без режима, вернёт фоновую
    модалку молча (та же механика потери политики, что у `swallow`
    и `failure_key` решения 0.5). Полнота карты заперта тестом
    `test_every_autosave_class_carries_the_mode`.
    """

    #: можно ли поднимать диалоги во время сохранения (жест оператора — можно)
    _save_interactive: bool = True

    #: чем кончилось сохранение без права спрашивать — строка оператору
    save_refusal: str = ""

    #: ЛИПКАЯ метка «буфер несвежий»: сервер отбил запись гейтом пересборки,
    #: и всё, что лежит во вкладке, считается против мёртвого поколения узлов.
    #: Снимается только пересозданием вкладки — это и есть «перезагрузите».
    save_blocked_reason: str = ""

    @contextmanager
    def non_interactive_save(self):
        """Сохранение БЕЗ вопросов: тик таймера, а не жест оператора.

        Прежнее значение возвращается, а не выставляется в `True`: право
        спрашивать принадлежит вкладке, и режим обязан его вернуть таким,
        каким взял.
        """
        previous = self._save_interactive
        self._save_interactive = False
        self.save_refusal = ""
        try:
            yield
        finally:
            self._save_interactive = previous

    def rebuild_banner(self, exc) -> str:
        """Отказ гейта пересборки → пометить буфер несвежим. Иначе — `""`.

        Зовётся из `except` каждого пути записи. Признак машинный (`ASCII` в
        `detail`), а не «сервер ответил 400»: у соседних отказов — «OCR result
        not available yet», слепая перезапись, битый JSON — правки оператора
        живы и лечатся повтором, морозить буфер там нельзя.

        Полное закрытие окна «после BUILT» (штамп поколения в самом графе) —
        кандидат в дорогу; здесь дешёвый заслон: пока вкладка жива, она больше
        не пишет, и автосохранение её не воскрешает.
        """
        if REBUILD_REFUSAL not in str(getattr(exc, "message", None) or exc):
            return ""
        self.save_blocked_reason = REBUILD_BANNER
        logger.warning("буфер %s uid=%s помечен несвежим: граф пересобран",
                       type(self).__name__, getattr(self, "uid", "?"))
        return REBUILD_BANNER

    def _refuse_save(self, text: str) -> None:
        """Сказать строкой то, что оператору сказал бы диалог.

        Строку показывает `AutoSaveService._on_tick`: своя строка вкладки
        точнее общего «⚠️ Автосохранение не удалось» — она называет причину,
        по которой запись не состоялась, и тем отличает отказ от поломки.
        """
        self.save_refusal = text
        logger.warning("автосохранение %s uid=%s: %s",
                       type(self).__name__, getattr(self, "uid", "?"), text)
