# -*- coding: utf-8 -*-
"""layout_gate.py — пускать ли оператора в «Ручную правку».

Решение заказчика 2026-07-28 (§3.2 плана docs/planning/
AUTO_LAYOUT_INTEGRATION.md): вкладка не открывается, пока не пройдена привязка
и не готова раскладка. Этот гейт и прячет 2-5 минут счёта — «не пускаем, пока
ты с текстом не поработаешь».

Состояние определяется **стадией `layout`**, а не наличием холста: отсутствие
файла неразличимо между «считает», «упала» и «не стартовала» (диспетчер при
недоступном брокере вернёт `dispatch_failed`, и никакого артефакта не будет).

⛔ **Ожидание с пределом больше НЕ открывает дверь** (решение Максима №9,
2026-08-25, блок 8 линии «Ручная правка + FXML»). Раньше и упавшая раскладка,
и просроченное ожидание пускали оператора внутрь: вкладка собирала аварийный
холст `pretransform`-ом (без раскладки) и он правил недосчитанное. Аварийного
холста больше нет (`base_graph_tab._canvas_verdict`), поэтому «пустить без
раскладки» стало «пустить в пустоту» — обе лазейки закрыты замком, который
называет причину и дверь повтора: «Контуры» → «Подтвердить» переставляет
задачу (после FAILED холст не написан, диспетчер посчитает заново). Размен
принят осознанно: схема, у которой раскладка падает всегда, остаётся без
«Ручной правки».

Модуль чистый (без Qt и без сети), чтобы правило проверялось тестом.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from typing import Optional

# Предел ожидания раскладки. Замер на dev-CPU: 936 узлов — 72 с; план
# оценивает боевой CPU-only в 2-5 мин. Лимит с запасом; уточняется тем же
# замером, что и `soft_time_limit` задачи (docs/AUTO_LAYOUT_E2E_TESTPLAN.md §5).
WAIT_LIMIT_S = 600.0

STAGE_TYPE = "layout"

# Статусы, при которых привязка уже пройдена и гейт по статусу открыт.
# OCR_COMPLETED в прямом конвейере не присваивается вовсе (OCR-таск статус не
# меняет) — он появляется только откатом бусины привязки, и оттуда оператор
# обязан пройти привязку заново.
_BOUND_STATUSES = ("ocr_bound", "generating_fxml", "completed")

# Дверь повтора — одна на все замки: закрытие «Контуров» диспатчит раскладку
# ВСЕГДА (`app/api/contours.py`), в отличие от прочих подтверждений фазы B.
# Прямого «пересчитать» с клиента нет и не заводится (решение №9).
RETRY_DOOR = "вернитесь в «Контуры» и нажмите «Подтвердить» — это запустит пересчёт"

# ⛔ ЧТО ДЕЛАТЬ, ЕСЛИ ДВЕРЬ НЕ СРАБОТАЛА. Диспетчер ставит задачу только когда
# истина СМЕНИЛАСЬ: на целом холсте под упавшей строкой стадии он отвечает
# ALREADY_FRESH, на зависшей задаче — ALREADY_RUNNING (`app/services/
# layout_policy.py`), и повторное подтверждение «Контуров» новой стадии не
# заводит. Замок тогда вечный, а выход один и дорогой. Решение Максима
# 2026-08-26 (к mefx-8): в этом состоянии в «Ручную правку» НЕ пускать —
# значит оператору обязаны назвать настоящую цену выхода, а не только дверь.
LOCK_DEAD_END = ("Если не помогло — пересчёт не запустится, пока схема не "
                 "изменится; вернуть вкладку можно только откатом до "
                 "«Проверки схемы», а он сотрёт холст и потребует заново "
                 "подтвердить привязку подписей.")


@dataclass
class GateState:
    """Что показывать на кнопке «Ручная правка»."""
    allow: bool                 # пускать во вкладку
    waiting: bool               # идёт счёт — кнопка с процентами, не серая
    reason: str                 # для тултипа, лога и сообщения оператору
    warn: Optional[str] = None  # предупреждение при входе (пускаем, но не всё гладко)


def _parse_dt(value):
    if isinstance(value, datetime):
        return value
    if not value:
        return None
    try:
        return datetime.fromisoformat(str(value).replace("Z", "+00:00").split("+")[0])
    except ValueError:
        return None


def latest_layout(stages):
    """Последняя строка стадии `layout` или None. Публичный вход для вкладки:
    экран ожидания отличает «стадии нет / сервер не ответил» от «стадия есть
    и она завершилась» — по первому он экран не двигает вовсе."""
    return _latest_layout(stages)


def _latest_layout(stages):
    rows = [s for s in (stages or [])
            if (s.get("stage_type") or "").lower() == STAGE_TYPE]
    if not rows:
        return None
    return max(rows, key=lambda s: s.get("id") or 0)


def layout_task_pending(stages) -> bool:
    """Задача раскладки РЕАЛЬНО поставлена или бежит (8.2).

    Отдельный вопрос от `gate_state`: гейт решает про кнопку, вкладка — про
    экран. «Холст устарел, а задачи нет» и «устарел, задача бежит» — разные
    исходы: первый ведёт дверью в «Контуры» (иначе ложь навечно), второй ждёт
    готовности. Смотрит ту же последнюю строку стадии, что и гейт.
    """
    row = _latest_layout(stages)
    return bool(row) and (row.get("status") or "").lower() in (
        "pending", "running")


def layout_wait_overdue(stages, *, now: Optional[datetime] = None,
                        wait_limit_s: float = WAIT_LIMIT_S) -> bool:
    """Бегущая раскладка считается ДОЛЬШЕ предела (для экрана ожидания).

    Отдельно от `gate_state`: тот решает про кнопку и на просрочке запирает, а
    экран уже открытой вкладки запирать некуда — ему нужно перестать обещать
    «схема откроется сама». Задача, зависшая насмерть (воркер убит, контейнер
    пересоздан), иначе держала бы обещание вечно.

    ⚠ Считается только от `started_at`: `created_at` до клиента не доезжает
    (см. `gate_state`), поэтому у задачи в очереди срок не наступает — и это
    честно: она ещё не начиналась.
    """
    row = _latest_layout(stages)
    if row is None or (row.get("status") or "").lower() not in (
            "pending", "running"):
        return False
    started = _parse_dt(row.get("started_at"))
    if started is None:
        return False
    return ((now or datetime.utcnow()) - started).total_seconds() > wait_limit_s


def gate_state(stages, status_value: str, *, now: Optional[datetime] = None,
               wait_limit_s: float = WAIT_LIMIT_S) -> GateState:
    """Пускать ли в «Ручную правку». status_value — значение DiagramStatus."""
    status = (status_value or "").lower()

    if status not in _BOUND_STATUSES:
        return GateState(
            False, False,
            "сначала подтвердите привязку подписей")

    row = _latest_layout(stages)
    if row is None:
        # Раскладки для этой схемы не заводилось: старая диаграмма или
        # диспетчер не сработал. Замок здесь был бы хуже отсутствия раскладки.
        return GateState(True, False, "раскладка не запускалась")

    st = (row.get("status") or "").lower()

    if st in ("pending", "running"):
        # Срок считается от `started_at`; `created_at` оставлен запасным
        # входом, но ⛔ ДО КЛИЕНТА ОН НЕ ДОЕЗЖАЕТ (см. ветку `else` ниже),
        # поэтому у задачи, застрявшей в очереди, отметок нет вовсе и предел
        # ожидания для неё не наступает — это и решает форма замка №9.
        started = _parse_dt(row.get("started_at")) or _parse_dt(
            row.get("created_at"))
        if started is not None:
            elapsed = ((now or datetime.utcnow()) - started).total_seconds()
            if elapsed > wait_limit_s:
                # ЗАМОК, а не вход без раскладки (решение №9): задача, висящая
                # дольше предела, холста не даст, а собирать аварийный нечем.
                return GateState(
                    False, False,
                    f"раскладка не посчиталась за "
                    f"{int(wait_limit_s // 60)} мин — {RETRY_DOOR}."
                    f"\n{LOCK_DEAD_END}")
        else:
            # Ни старта, ни создания — судить о СРОКЕ нечем, и запирать нельзя.
            # ⛔ Замер §MEFX8: `created_at` до клиента НЕ ДОЕЗЖАЕТ ВОВСЕ —
            # `/api/diagrams/{uid}/stages` его не отдаёт (`ProcessingStageResponse`,
            # `app/api/diagrams.py:326-339`), поэтому строка выше про «отсчёт от
            # created_at» на боевом пути мертва, а ЭТА ветка — живая для каждой
            # задачи, стоящей в очереди (`started_at` пишет только воркер, на
            # старте). Замок здесь стал бы вечным: без отметок предел ожидания
            # не наступает никогда. Дверь открыта, а честный ответ даёт сама
            # вкладка — экран ожидания вместо аварийного холста
            # (`base_graph_tab._show_canvas_gate`); модалки «схема откроется
            # как есть» больше нет, потому что это перестало быть правдой.
            return GateState(
                True, False, "раскладка поставлена, но ещё не начиналась")
        return GateState(False, True, "идёт раскладка схемы")

    if st == "failed":
        return GateState(
            False, False,
            "раскладка не удалась: " + (row.get("error_message") or
                                        "причина неизвестна") +
            f" — {RETRY_DOOR}.\n{LOCK_DEAD_END}")

    # completed / skipped: считать больше нечего. SKIPPED — штатный исход
    # гонки (истина сменилась или холст правился руками), и он тоже значит
    # «ждать нечего»: если поставлена новая задача, она и будет последней.
    return GateState(True, False, f"раскладка: {st}")
