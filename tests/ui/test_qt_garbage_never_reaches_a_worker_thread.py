# -*- coding: utf-8 -*-
"""Сторож обстановки: Qt-мусор не доживает до чужой нити.

Стережёт решение `tests/ui/conftest.py`, а не свойство Qt (`PROTOCOL §3`).
Решений там два, и утверждается каждое:

* **автоматический сборщик снят с чужих нитей.** Иначе он приходит за
  брошенной вкладкой в нити пула загрузчика — наблюдение прямое, `gc.callbacks`
  на полном прогоне: девять проходов с именами `ThreadPoolExecutor-*`, все
  в файлах-копителях вкладок. Разрушение `QWidget` не в его потоке портит
  внутренние списки Qt, и процесс падает `0xC0000005` у того, кто СЛЕДУЮЩИМ
  тронет Qt-мир, — вплоть до простого чтения `QApplication.allWidgets()`;
* **то, что набор попросил снести, действительно сносится** — между тестами
  и в главном потоке. `qapp.processEvents()`, которым это делают десять
  наборов, `DeferredDelete` не доставляет ВОВСЕ (замер 1-42, §95д).

⛔ Второе утверждение сделано ПАРОЙ тестов, и иначе его не сделать: уборка
идёт в `pytest_runtest_teardown`, то есть тест не может наблюдать собственную
уборку. Первый просит снести виджет и держит на него СИЛЬНУЮ ссылку (чтобы
судить доставку события, а не работу сборщика), второй проверяет, что
C++-объекта больше нет. Порядок тестов в файле — исходный, это контракт pytest.

⚠ Обе половины проверены инъекцией и краснеют по отдельности: без
`tests/ui/conftest.py` красны первый и третий тесты, второй остаётся зелёным —
он обстановка, а не утверждение.

⚠ Чего сторож НЕ утверждает: он ничего не говорит о доле крахов на полном
прогоне — та популяция мерится прогонами, а не утверждением в тесте
(`MEASUREMENTS §119.12`, та же граница).
"""
import gc
import os

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

import pytest                                            # noqa: E402

pytest.importorskip("PySide6")

from PySide6.QtWidgets import QApplication, QWidget      # noqa: E402
from shiboken6 import isValid                            # noqa: E402

#: Виджет, который предыдущий тест попросил снести. Ссылка СИЛЬНАЯ намеренно:
#: сборщику он так не достанется, и сторож судит именно доставку
#: `DeferredDelete`, а не работу `gc`.
_asked_to_go: list = []


@pytest.fixture(scope="module")
def qapp():
    return QApplication.instance() or QApplication([])


def test_the_collector_is_taken_off_the_worker_threads(qapp):
    """Автоматический сборщик выключен, пока идут UI-наборы.

    Наблюдаемое — состояние самого сборщика, а не число его проходов: доля
    проходов вероятностна, а этот флаг — то самое решение, которым она
    обнуляется (замер: 13–16 проходов в чужой нити на пяти файлах-копителях
    против 0 после правки, по три захода на полярность).
    """
    assert not gc.isenabled(), (
        "автоматический сборщик включён во время UI-набора: он вправе "
        "сработать в нити пула загрузчика и снести там брошенную вкладку. "
        "Снимает его `tests/ui/conftest.py`"
    )


def test_a_widget_asked_to_go_waits_for_the_sweep(qapp):
    """Обстановка для следующего теста: `deleteLater()` без оборота очереди."""
    widget = QWidget()
    widget.deleteLater()
    _asked_to_go.append(widget)

    assert isValid(widget), (
        "виджет снесён прямо здесь — значит очередь кто-то провернул, "
        "и обстановка не собралась"
    )


def test_the_sweep_delivered_the_deferred_delete(qapp):
    """Между тестами просьбу снести доставили — здесь и в главном потоке."""
    assert _asked_to_go, "предыдущий тест виджета не оставил"
    assert not isValid(_asked_to_go[-1]), (
        "виджет, который просили снести, дожил до следующего теста: "
        "отложенное удаление в очереди никто не доставил. Так набор копит "
        "живые вкладки, а сносит их потом сборщик — в той нити, где сработал "
        "порог (`tests/ui/conftest.py`)"
    )
