# -*- coding: utf-8 -*-
"""Обстановка UI-наборов: Qt-мир убирается МЕЖДУ тестами и в ГЛАВНОМ потоке.

⛔ **Это корень крахов базового гейта `0xC0000005`, который дорога до сих пор
записывала как НЕ НАЙДЕННЫЙ** (`MEASUREMENTS §119.14.1`: «названы класс кадра,
доля 4/4 и четыре опровергнутые ветки поиска; механизм не установлен»).
Найден он не рассуждением, а наблюдением — журналом на каждый тест полного
прогона плюс `gc.callbacks`.

Механизм — три звена, и ни одно из них само по себе не дефект:

1. **UI-наборы бросают настоящие вкладки живыми.** Форма
   `tab.deleteLater()` + `qapp.processEvents()` стоит в десяти файлах, а
   `processEvents()` `DeferredDelete` не доставляет ВОВСЕ (замер 1-42, §95д);
   ещё два файла (`test_download_failure_is_visible.py`,
   `test_contour_partial_save.py`) зовут только `tab.cleanup()`. Замерено
   счётчиком `QApplication.allWidgets()` после каждого из 2840 тестов полного
   прогона: после `test_binding_tab_download_failure.py` живых виджетов
   **1295** (37 верхнего уровня), после `test_download_failure_is_visible.py`
   — **830**, пик по прогону — **1427**.

2. **Эти вкладки — мусор в питоньем смысле, и уносит их СБОРЩИК**, а не Qt:
   ссылок на них нет, но они в циклах (связи сигналов, родитель↔ребёнок,
   замыкания), поэтому refcount их не берёт. Момент сборки не назначает никто.

3. ⛔ **Сборщик срабатывает в НИТИ ПУЛА загрузчика артефактов.** Наблюдение
   прямое, `gc.callbacks` на полном прогоне: **девять** проходов сборщика вне
   главного потока с именами `ThreadPoolExecutor-*` (нити
   `ui/services/artifact_downloader.py:222`), собрано 33…632 объекта за проход,
   и все девять — РОВНО в тех четырёх файлах, что копят вкладки
   (`test_artifact_downloader`, `test_autosave_non_interactive`,
   `test_binding_tab_download_failure`, `test_download_failure_is_visible`).
   Разрушение `QWidget` не в его потоке — это порча внутренних списков Qt.

Отсюда всё, что дорога наблюдала сутки и не могла объяснить: **имена плавают,
кадр — нет.** Падает не тот, кто испортил, а тот, кто ПЕРВЫМ после этого
трогает Qt-мир: `processEvents()` у `_pump`/`_join`, или даже простое чтение
`QApplication.allWidgets()` — в контрольном прогоне этой сессии крах пришёл
именно на чтение списка виджетов, то есть в списке уже лежал висячий указатель.

Лечение здесь **не добавляет ни одного нового разрушения** — и это существенно,
потому что «убирать вкладки в наборах» замерено как ВРЕДНОЕ (§95и, §102и:
0 зелёных из 4). Оно переносит разрушение, которое и так произойдёт, в
известный момент и в правильный поток: между тестами, в главном потоке.
`sendPostedEvents(None, DeferredDelete)` доставляет то, что наборы уже
попросили снести (и чего `processEvents()` им не доставил), а `gc.collect()`
не даёт накопиться мусору, за которым придёт чужая нить.

⚠ Границы, которых уборка НЕ закрывает и на которые не претендует:

* она не чинит сами наборы — двенадцать файлов по-прежнему оставляют вкладки
  живыми до конца теста; адреса названы выше, правка их teardown — за
  владельцами зон;
* она не трогает боевой код. Тот же класс (питоний сборщик уносит Qt-объект
  чужой нитью) в клиенте возможен и лечится не здесь;
* `QApplication.allWidgets()` к концу прогона всё равно не ноль: часть виджетов
  удержана модульными фикстурами, то есть это не мусор, и сборщику они
  не достаются.
"""
from __future__ import annotations

import gc

import pytest

#: Был ли автоматический сборщик включён до нас (`None` — мы его ещё не трогали).
_gc_was_enabled: bool | None = None


def _take_gc_off_the_worker_threads() -> None:
    """Снять у сборщика право сработать в ЧУЖОЙ нити.

    ⛔ Одного `gc.collect()` между тестами мало, и это замерено: он уменьшает
    мусор, но не запрещает автоматическому проходу случиться ВНУТРИ теста и
    ВНУТРИ нити пула. Подсчёт `gc.callbacks` на трёх файлах-копителях:
    без уборки — **10** проходов вне главного потока, с одной только уборкой
    — **3**, с выключенным автоматическим сборщиком — **0**.

    Ручной `gc.collect()` при этом продолжает работать, поэтому мусор не
    копится: он собирается после каждого теста, здесь же, в главном потоке.
    """
    global _gc_was_enabled
    if _gc_was_enabled is None:
        _gc_was_enabled = gc.isenabled()
        gc.disable()


def _sweep() -> None:
    """Снести всё, что уже стало мусором, — здесь и в этом потоке."""
    try:
        from PySide6.QtCore import QEvent
        from PySide6.QtWidgets import QApplication
    except ImportError:                      # набор без Qt — убирать нечего
        return

    if QApplication.instance() is not None:
        # То, что набор уже попросил снести. `processEvents()` этого
        # не доставляет вовсе (замер 1-42, §95д), поэтому адресно.
        QApplication.sendPostedEvents(None, QEvent.Type.DeferredDelete)

    # И только теперь сборщик — в ГЛАВНОМ потоке, а не в нити пула.
    gc.collect()


@pytest.hookimpl(tryfirst=True)
def pytest_runtest_setup(item):
    """Первый же UI-тест снимает автоматический сборщик с чужих нитей.

    Здесь, а не в `pytest_configure`: сбор всей базы идёт ДО первого теста и
    сам по себе создаёт циклы, а Qt-мусора в этот момент нет вовсе — платить
    памятью за сбор незачем.
    """
    _take_gc_off_the_worker_threads()


@pytest.hookimpl(wrapper=True)
def pytest_runtest_teardown(item, nextitem):
    """Уборка идёт ПОСЛЕ всех финализаторов теста, а не вместо них.

    Хук, а не `autouse`-фикстура: у фикстуры порядок финализации зависит от
    того, кто кого запросил, а здесь нужно место, где точно отработали ВСЕ
    фикстуры теста — иначе вкладка, которую сносит чужой финализатор, до
    уборки не доживёт и станет мусором уже после неё.
    """
    try:
        return (yield)
    finally:
        _sweep()


def pytest_sessionfinish(session, exitstatus):
    """Вернуть сборщик как было: процесс наш, но привычки его — не наши."""
    global _gc_was_enabled
    if _gc_was_enabled:
        gc.enable()
    _gc_was_enabled = None
