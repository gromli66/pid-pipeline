"""_gap.py — детектор дефекта: ЗНАКОВЫЙ зазор между формами концов ребра.

Источник: стенд `_scratch/layout_align/diag_realgap.py` (строки 51-90).
Перенесено без изменения логики — см. docs/planning/AUTO_LAYOUT_INTEGRATION.md, Э2.
Мерить нарисованную длину полилинии нельзя: её подделывает посадка концов
(схлопнутая вертикальная подводка рисуется отрезком 10.5 px вдоль кромки —
32 дефекта на 51b339ab были невидимы для собственной диагностики стенда).
Зазор между формами подделать нечем: это то, что видит глаз.
"""
from __future__ import annotations

import math

from ..graph_access import is_connector, node_cxy

FLOOR = 6.0        # px: порог видимости трубы (0.75 * min_gap)

def shape_box(n):
    """Форма узла как прямоугольник; коннектор — вырожденный (точка)."""
    cx, cy = node_cxy(n)
    bb = n.get("bbox")
    if is_connector(n) or not bb or len(bb) != 4 or bb[2] <= bb[0] \
            or bb[3] <= bb[1]:
        return (cx, cy, cx, cy)
    return (bb[0], bb[1], bb[2], bb[3])


def gap_and_seam(a, b):
    """Зазор между формами (ЗНАКОВЫЙ) и ОТРЕЗОК ЩЕЛИ (ближайшие точки).

    -> (gap_px, (x1, y1), (x2, y2)).
    gap > 0 — столько пустого места между формами;
    gap = 0 — касание;
    gap < 0 — ПЕРЕКРЫТИЕ, и модуль равен ГЛУБИНЕ проникновения (минимальный
    сдвиг, которым формы расцепляются; для коннектора внутри бокса — это
    расстояние до ближайшей кромки).

    Знак нужен, потому что бинарный ноль скрывал ухудшение: ход «зазор 0.00 ->
    0.00» проходил как «не хуже», хотя коннектор из положения НА кромке
    переезжал ВНУТРЬ бокса (замер node_576/node_586: клапан опустился на 12px
    и накрыл коннектор, счётчик этого не увидел).
    """
    ax1, ay1, ax2, ay2 = a
    bx1, by1, bx2, by2 = b
    ox = max(bx1 - ax2, ax1 - bx2)
    oy = max(by1 - ay2, ay1 - by2)
    if ox <= 0.0 and oy <= 0.0:      # перекрытие по обеим осям
        px1 = min(max((bx1 + bx2) / 2.0, ax1), ax2)
        py1 = min(max((by1 + by2) / 2.0, ay1), ay2)
        return -min(-ox, -oy), (px1, py1), (px1, py1)
    dx = max(ox, 0.0)
    dy = max(oy, 0.0)
    px1 = min(max((bx1 + bx2) / 2.0, ax1), ax2)
    py1 = min(max((by1 + by2) / 2.0, ay1), ay2)
    px2 = min(max(px1, bx1), bx2)
    py2 = min(max(py1, by1), by2)
    return math.hypot(dx, dy), (px1, py1), (px2, py2)
