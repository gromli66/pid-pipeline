# -*- coding: utf-8 -*-
"""params.py — пороги раскладки одним объектом.

Значения — из §6.5 `_scratch/layout_align/SOLUTION.md`, то есть ровно те, на
которых посчитан эталон корпуса (588 -> 20 дефектов). Менять их без
перезамера `tools/layout_bench.py` нельзя.

ВЫВЕРКА ГЛАЗАМИ НЕ ПРОЙДЕНА для `pen_tol`, `order_near`, `tail_max` и величины
рамки: они откалиброваны на одном графе (51b339ab) и заказчиком не смотрены
(Э7 п. 1 плана). В `configs/projects/*.yaml` выносить только после неё.

Часть полей помечена ниже как ЗАМОРОЖЕННЫЕ: перенесённый со стенда слой
раздвигания захватил их дефолтами аргументов на импорте, поэтому изменить их
через этот объект нельзя. Попытка задать другое значение падает с явным
сообщением (`layout._apply`), а не игнорируется молча; чтобы их разморозить,
надо править сигнатуры в `layout/spread.py` — это работа Э7, вместе с выносом
порогов в конфиг.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass
class LayoutParams:
    """Пороги раскладки. Все размеры — в пикселях холста 1920x1080."""

    # ─── геометрия листа ───
    canvas: tuple = (1920.0, 1080.0)   # ЗАМОРОЖЕН для слоя раздвигания
    margin: float = 24.0      # рамка листа. Решение заказчика: «плохо читается,
                              # когда ровно к краям». Одно число на оба слоя —
                              # поле расстановки (inset) и запрет выхода при
                              # раздвигании; в эталонном прогоне они равны.

    # ─── детектор дефекта ───
    floor: float = 6.0        # порог видимости трубы (0.75 * min_gap)
    target: float = 12.0      # желаемая длина трубы (порог заказчика)

    # ─── лестница механизмов ───
    skew_max: float = 16.0    # скос, который выпрямляем (замер насыщения:
                              # 5->9, 8->7, 12->7, 16->6, 20->6, 24->6)
    compound_max: float = 40.0  # выше — честная диагональ схемы, не сбитая ось
    tail_max: int = 12        # узлов: граница «концевая ветка / середина графа»
    grow_max: int = 80        # ЗАМОРОЖЕН. Узлов: предохранитель против куста
                              # размером в пол-листа
    passes: int = 14          # максимум проходов (сходится сам за 1-3)

    # ─── приёмка ───
    pen_tol: float = 12.0     # ЗАМОРОЖЕН. Допуск на суммарное ухудшение
                              # глубины по листу («не прям сильно»)
    order_tie: float = 6.0    # ЗАМОРОЖЕН. Ниже — узлы стоят вровень, порядок
                              # не установлен
    order_near: float = 100.0  # ЗАМОРОЖЕН. Дальше — пары визуально несравнимы

    # ─── перенос полос ───
    band: str = "both"        # both | pre | post | off
    band_reach: float = 600.0  # докуда искать компенсирующий разрез (насыщение)
    band_tries: int = 16
    band_rounds: int = 3      # ЗАМОРОЖЕН

    # ─── форма узла и легальные наложения ───
    shape_overlaps: bool = True   # наложения считать по РЕАЛЬНОЙ форме узла
                              # (segmentation, иначе bbox) и не разводить пары,
                              # наложенные в ДЕТЕКТИРОВАННОЙ геометрии — решение
                              # заказчика «наложения из построения и проверки
                              # легальны». False — прежнее поведение по
                              # габаритам, нужно для сверки бит-в-бит.
    border_tol: float = 3.0   # px: «узел стоит на границе фигуры» — тоже
                              # легально. Замер: 9 из 20 угловых узлов на
                              # c2f79462 в 0.31-2.46 px от контура (шум
                              # трассировки), следующий на 10.64; tol=6 даёт
                              # тот же результат — порог на плато.

    band_block: bool = True   # СТВОР КРУПНОГО БЛОКА: ось партнёра держится в
                              # полосе габарита блока парой встречных
                              # неравенств яруса 1 (`axial.build_bands`).
                              # Включено решением заказчика 2026-07-30 при
                              # замеренном размене: косых рёбер по корпусу
                              # 60 -> 53 и на c2f79462 2 -> 1, ценой двух
                              # дефектов (13d1ef5f 22->2 становится 23->3,
                              # c2f79462 13->3 становится 13->4; на 8d517a35
                              # бесплатно — косых 20 -> 16 при 0 дефектов).
                              # Приёмка 590 -> 14 становится 592 -> 15.
                              # На пяти графах из восьми механизм не
                              # запускается вовсе: крупного контурного блока
                              # нет, полосы не строятся, координаты узлов
                              # совпадают с выключенным режимом БИТ-В-БИТ
                              # (отпечатки 5c9cf120483a3133, 0b1e7295950c845d,
                              # 8055993182ee36cc, 6e3e7493854dc215,
                              # 10ce37569fd6047e). Время не меняется.

    # ─── этап роутинга (Э7-b) ───
    routing: bool = True      # обход чужих форм libavoid ПОСЛЕ раздвигания:
                              # рёбра получают waypoints, узлы не двигаются.
                              # Работает только при доступном биндинге
                              # (`_avoid_binding.avoid_available`), итог судит
                              # trial-and-revert «не хуже входа» — поэтому
                              # дефолт True осознанный (Э7-b): выход раскладки
                              # меняется, magi-остаток закрывается обходом.
    route_buffer: float = 6.0  # px, shapeBufferDistance libavoid: клиренс
                              # маршрута от чужих форм. = floor (порог
                              # видимости трубы): зазор тоньше порога глаз
                              # уже не читает, а больший буфер закрывает
                              # коридоры в плотной схеме (зазоры target=12).
    route_nudge: float = 8.0  # px, idealNudgingDistance libavoid: разведение
                              # параллельных пробегов. Между floor (6) и
                              # target (12): разведённые трубы читаются
                              # раздельно, но жгут не расползается на соседей.

    # ─── редко трогаемое ───
    fill: float = 1.0         # доля заполнения холста расстановкой
    unlock_zero: bool = False
    compound: bool = True
    comp_push: bool = False
