# -*- coding: utf-8 -*-
"""params.py — пороги раскладки одним объектом.

Значения — из §6.5 `_scratch/layout_align/SOLUTION.md`, то есть ровно те, на
которых посчитан эталон корпуса (588 -> 20 дефектов). Менять их без
перезамера `tools/layout_bench.py` нельзя.

ВЫВЕРКА ГЛАЗАМИ НЕ ПРОЙДЕНА для `pen_tol`, `order_near`, `tail_max` и величины
рамки: они откалиброваны на одном графе (51b339ab) и заказчиком не смотрены
(Э7 п. 1 плана). В `configs/projects/*.yaml` выносить только после неё.

Часть полей помечена ниже как ЗАМОРОЖЕННЫЕ: перенесённый со стенда слой
раздвигания захватил их дефолтами аргументов на импорте, поэтому изменить их
через этот объект нельзя. Попытка задать другое значение падает с явным
сообщением (`layout._apply`), а не игнорируется молча; чтобы их разморозить,
надо править сигнатуры в `layout/spread.py` — это работа Э7, вместе с выносом
порогов в конфиг.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass
class LayoutParams:
    """Пороги раскладки. Все размеры — в пикселях холста 1920x1080."""

    # ─── геометрия листа ───
    canvas: tuple = (1920.0, 1080.0)   # ЗАМОРОЖЕН для слоя раздвигания
    margin: float = 24.0      # рамка листа. Решение заказчика: «плохо читается,
                              # когда ровно к краям». Одно число на оба слоя —
                              # поле расстановки (inset) и запрет выхода при
                              # раздвигании; в эталонном прогоне они равны.

    # ─── детектор дефекта ───
    floor: float = 6.0        # порог видимости трубы (0.75 * min_gap)
    target: float = 12.0      # желаемая длина трубы (порог заказчика)

    # ─── лестница механизмов ───
    skew_max: float = 16.0    # скос, который выпрямляем (замер насыщения:
                              # 5->9, 8->7, 12->7, 16->6, 20->6, 24->6)
    compound_max: float = 40.0  # выше — честная диагональ схемы, не сбитая ось
    tail_max: int = 12        # узлов: граница «концевая ветка / середина графа»
    grow_max: int = 80        # ЗАМОРОЖЕН. Узлов: предохранитель против куста
                              # размером в пол-листа
    passes: int = 14          # максимум проходов (сходится сам за 1-3)

    # ─── приёмка ───
    pen_tol: float = 12.0     # ЗАМОРОЖЕН. Допуск на суммарное ухудшение
                              # глубины по листу («не прям сильно»)
    order_tie: float = 6.0    # ЗАМОРОЖЕН. Ниже — узлы стоят вровень, порядок
                              # не установлен
    order_near: float = 100.0  # ЗАМОРОЖЕН. Дальше — пары визуально несравнимы

    # ─── перенос полос ───
    band: str = "both"        # both | pre | post | off
    band_reach: float = 600.0  # докуда искать компенсирующий разрез (насыщение)
    band_tries: int = 16
    band_rounds: int = 3      # ЗАМОРОЖЕН

    # ─── редко трогаемое ───
    fill: float = 1.0         # доля заполнения холста расстановкой
    unlock_zero: bool = False
    compound: bool = True
    comp_push: bool = False
